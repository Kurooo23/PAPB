  static List<String> get leagues => data.keys.toList();

  static List<String> getDivisions(String league) {
    if (!data.containsKey(league)) {
      return data['Liga Inggris']!.keys.toList();
    }
    return data[league]!.keys.toList();
  }

  static List<String> getClubs(String league, String division) {
    if (!data.containsKey(league)) league = 'Liga Inggris';
    if (!data[league]!.containsKey(division)) {
      division = data[league]!.keys.first;
    }
    return data[league]![division]!;
  }

  static Map<String, String> getRandomAll() {
    final allLeagues = leagues;
    final randomLeague = allLeagues[_random.nextInt(allLeagues.length)];
    final allDivisions = getDivisions(randomLeague);
    final randomDivision = allDivisions[_random.nextInt(allDivisions.length)];
    final allClubs = getClubs(randomLeague, randomDivision);
    final randomClub = allClubs[_random.nextInt(allClubs.length)];

    return {
      'league': randomLeague,
      'division': randomDivision,
      'club': randomClub,
    };
  }

