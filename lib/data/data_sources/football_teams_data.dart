  static String sanitizeSlug(String text) {
    return text.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]'), '_').replaceAll(RegExp(r'_+'), '_').replaceAll(RegExp(r'^_|_$'), '');
  }

  static String getLocalAssetPath(String teamName, String leagueName) {
    if (leagueName == 'Tim Nasional') {
      final cleanName = teamName.replaceFirst('Timnas ', '').trim();
      final slug = sanitizeSlug(cleanName);
      return 'assets/images/logos/flags/$slug.png';
    }
    final slug = sanitizeSlug(teamName);
    return 'assets/images/logos/clubs/$slug.png';
  }

  static String? getTeamLogoUrl(String teamName, String leagueName) {
    if (leagueName == 'Tim Nasional') {
      final cleanName = teamName.replaceFirst('Timnas ', '').trim();
      final code = countryFlagCodes[cleanName];
      if (code != null) {
        return 'https://flagcdn.com/w160/$code.png';
      }
      return null;
    }

    final id = clubLogoIds[teamName];
    if (id != null) {
      return 'https://images.fotmob.com/image_resources/logo/teamlogo/$id.png';
    }
    return null;
  }

